"""Schedule-revenue-total fix -- PART 1.

Root cause (confirmed against real data): every revenue function's
"no job.price? fall back to the client's price" step reads from
CLIENT_PRICES/REV_LOOKUP -- both declared as permanently empty objects
since the multi-tenant migration (v11.0.3 comments: "Manna-specific
price fallback retired; clients/jobs.price is authoritative"). So for
years the fallback has been dead: any job with no price ever silently
contributed $0, with zero fallback and zero visible warning. Today
(2026-11-16) four jobs were added manually late the night before
(create path doesn't fill in a price the way auto-generated jobs do)
and landed with price=null -- their real prices ($300+$356+$374+$237
= $1,267) never made it into the $4,666 total Tom saw, which should
have been at least $5,933.

Fix: _pentaResolveJobPrice(j) is the ONE shared per-job price
resolver -- job.price wins whenever it's actually set (even an
explicit $0, a deliberate comp/free clean, is never silently
"corrected" back up), and only a genuinely missing price falls back
to the client's REAL current_price (read live off the client record,
not the dead legacy objects). Returns {amount, missing} so a caller
can tell "no price found anywhere" apart from "legitimately free."

getDayRevenue keeps its exact existing signature/filter rules
(unchanged: date match, not auto-generated, not cancelled, past-day
done-only, paused/inactive client exclusion) but now delegates its
per-job pricing to the shared resolver via _getDayRevenueDetail,
which also reports which jobs (if any) had no usable price at all --
updateRevDisplay uses this to show a visible "N jobs have no price"
indicator instead of ever silently coming up short again.
"""
