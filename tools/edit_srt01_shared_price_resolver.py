NEW_UPDATE_REV_DISPLAY = """function updateRevDisplay() {
  const el = document.getElementById('cal-day-rev');
  if (!el) return;
  let rev = 0, label = '';
  var missingJobs = [];
  if (revMode === 'day') {
    var _dayDetail = _getDayRevenueDetail(dateKey(calDate));
    rev = _dayDetail.total;
    missingJobs = _dayDetail.missingJobs;
    label = rev > 0 ? '$' + rev.toLocaleString('en-US', {maximumFractionDigits:0}) + ' ▸' : '▸';
  } else if (revMode === 'week') {
    rev = getWeekRevenue(calDate);
    label = rev > 0 ? 'Wk $' + rev.toLocaleString('en-US', {maximumFractionDigits:0}) + ' ▸' : '▸';
  } else {
    rev = getMonthRevenue(calDate);
    label = rev > 0 ? 'Mo $' + rev.toLocaleString('en-US', {maximumFractionDigits:0}) + ' ▸' : '▸';
  }
  el.textContent = label;
  _renderRevMissingPriceBadge(missingJobs);
}

// Schedule-revenue-total fix: a small, tappable "N jobs have no price"
// indicator next to the day total -- shown ONLY in day mode (week/month
// aggregate many days, each already counted correctly by the shared
// resolver above; the day view is where Tom actually compares the
// number against his own tally). Tapping it lists exactly which jobs,
// so the total can never be short with no visible trace of why.
function _renderRevMissingPriceBadge(missingJobs) {
  var badge = document.getElementById('cal-day-rev-missing');
  if (!badge) return;
  if (revMode !== 'day' || !missingJobs || !missingJobs.length) { badge.style.display = 'none'; badge.onclick = null; return; }
  badge.style.display = 'inline';
  badge.textContent = missingJobs.length + (missingJobs.length === 1 ? ' job has no price ⚠️' : ' jobs have no price ⚠️');
  badge.onclick = function (e) {
    e.stopPropagation();
    var lines = missingJobs.map(function (j) {
      var name = j.clientName || (j.clientId ? ('client ' + j.clientId) : 'unknown client');
      return name + (j.team ? ' (' + j.team + ')' : '') + ' — not counted in the total above';
    });
    alert('No price on file -- not included in the total:\\n\\n' + lines.join('\\n'));
  };
}"""

