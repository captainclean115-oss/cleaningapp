-- Phone + password login (PR: phone-password-login).
--
-- No new table and no rate-limit table: the existing generic
-- rate_limit_check/rate_limit_increment RPCs (migration 066, already
-- used by send-sms with the exact same string-key pattern) are reused
-- directly by the new phone-login and request-password-reset Edge
-- Functions -- "login:phone:<10digits>", "reset:phone:<10digits>",
-- "reset:ip:<ip>". Nothing to create for that here.
--
-- What this migration DOES do: an index to make the phone-number lookup
-- (every login, every reset request) cheap, and a documented decision
-- NOT to add a database-level uniqueness constraint on phone yet.
--
-- Read-only audit (2026-10-20), confirmed live: Blanca Payan and
-- Viviana, both currently ACTIVE employees, normalize to the SAME
-- 10-digit phone number (7816263485 — Viviana's raw value has a leading
-- "1" country code, Blanca's doesn't). A hard UNIQUE constraint on
-- normalized phone would FAIL TO APPLY right now because live data
-- already violates it. Enforcement stays application-level for now:
-- pentaSendInvite() refuses to send a NEW invite when the phone is
-- shared with another active employee (see index.html), and the Staff
-- screen shows a visible "(shared)" warning on both existing rows. The
-- two EXISTING accounts are unaffected — phone-login tries each
-- matching employee's own password in turn, so each person still only
-- gets into HER OWN account with HER OWN password; this is a workaround
-- for existing data, not a security hole (see phone-login's own file
-- comment for the exact reasoning).
--
-- Once Blanca/Viviana's numbers are fixed by hand, a FOLLOW-UP migration
-- can add:
--   CREATE UNIQUE INDEX idx_employees_phone_active_unique
--     ON public.employees (business_id, regexp_replace(phone, '[^0-9]', '', 'g'))
--     WHERE status = 'active' AND phone IS NOT NULL;
-- Not applied here — would fail today for the reason above.
CREATE INDEX IF NOT EXISTS idx_employees_phone_lookup
  ON public.employees (business_id, phone)
  WHERE phone IS NOT NULL;

